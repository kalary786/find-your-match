<h2 id="prohibited">What is prohibited</h2>
<p>Find Your Match has no tolerance for CSAE. You may not create, upload, request, or share:</p>
<ul>
    <li>Child sexual abuse material (CSAM), meaning any photo, video, or computer-generated image of a person under 18 in sexually explicit conduct.</li>
    <li>Sexual content, sexual requests, or sexual conversation involving anyone under 18.</li>
    <li>Grooming, or any attempt to meet, contact, or exploit a child.</li>
    <li>A profile, photo, or chat that presents someone as under 18, or that sexualizes a minor.</li>
