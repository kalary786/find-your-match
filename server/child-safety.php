<h2 id="age">Adults only</h2>
<p>Find Your Match is an 18+ dating and social matching app. It is not for children, and it is not directed at anyone under 18. A date of birth under 18 is rejected. Age is calculated on the server from the date of birth you type. The app does not check an identity document. If we learn an account is under 18, we delete it.</p>
<h2 id="report">How to report</h2>
<p>The app has an in-app report. Open the person’s profile, or the menu in a chat, and tap Report. Choose Child safety, Inappropriate photo, or Other, and write what you saw. You can also block that person. Reports are stored for an admin to review. Do not copy or forward the content.</p>
<h2 id="action">What we do after we know</h2>
<p>When we obtain actual knowledge of CSAM or other CSAE on Find Your Match, we remove the content, block or delete the account, and sign that person out. An admin can also delete the related chat. We report confirmed CSAM to the National Center for Missing and Exploited Children (NCMEC) or the relevant regional authority, and we keep what that report requires.</p>
<h2 id="laws">Child safety laws</h2>
<p>Find Your Match follows applicable child safety laws and regulations. That includes a process to report confirmed CSAM to NCMEC or the relevant regional authority.</p>
<h2 id="contact">Child safety contact</h2>
<p>Google Play can write to the child safety point of contact named for Find Your Match in Play Console. That contact can speak to these standards and can remove content, block an account, or delete it. People using the app should use Report. Do not send images of a child to the contact or to anyone else.</p>
